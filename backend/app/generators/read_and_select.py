"""Real and fake words for Read and Select.

Real words come from the curated list in content/words.json. Fake words are generated by a
character trigram model trained on English words, then rejected if they appear anywhere in
the wordfreq dictionary (which also contains names and slang), so they look English but are not.
"""

import random
import re
from collections import Counter, defaultdict
from functools import lru_cache

from wordfreq import top_n_list, zipf_frequency

from ..content import load

START, END = "^^", "$"
WORDS_PER_SET = 18

# Consonant clusters English words can start with; anything else (like "pt" or "mc") looks foreign.
ONSETS = {
    "bl", "br", "ch", "cl", "cr", "dr", "dw", "fl", "fr", "gl", "gr", "kn", "ph", "pl", "pr",
    "qu", "sc", "sh", "sk", "sl", "sm", "sn", "sp", "st", "sw", "th", "tr", "tw", "wh", "wr",
    "scr", "shr", "spl", "spr", "squ", "str", "thr",
}


@lru_cache
def _trigram_model() -> dict[str, Counter]:
    corpus = [w for w in top_n_list("en", 30000) if re.fullmatch(r"[a-z]{4,12}", w)]
    model: dict[str, Counter] = defaultdict(Counter)
    for word in corpus:
        padded = START + word + END
        for i in range(len(padded) - 2):
            model[padded[i:i + 2]][padded[i + 2]] += 1
    return model


@lru_cache
def _real_words() -> frozenset[str]:
    data = load("words")
    return frozenset(w for level in ("easy", "medium", "hard") for w in data[level])


def _sample(rng: random.Random) -> str:
    model = _trigram_model()
    context, out = START, ""
    while len(out) < 14:
        counter = model[context]
        letters, weights = zip(*counter.items())
        nxt = rng.choices(letters, weights)[0]
        if nxt == END:
            break
        out += nxt
        context = context[1] + nxt
    return out


def _onset_ok(word: str) -> bool:
    onset = re.match(r"[^aeiouy]*", word).group(0)
    return len(onset) <= 1 or onset in ONSETS


def is_plausible_fake(word: str) -> bool:
    return (
        5 <= len(word) <= 10
        and re.search(r"[aeiouy]", word) is not None
        and re.search(r"(.)\1\1", word) is None
        and re.search(r"[^aeiouy]{4}", word) is None
        and re.search(r"[^aeiouy]{3}$", word) is None
        and _onset_ok(word)
        and word not in _real_words()
        and zipf_frequency(word, "en") == 0
    )


def fake_words(rng: random.Random, count: int) -> list[str]:
    words: list[str] = []
    for _ in range(count * 200):
        candidate = _sample(rng)
        if is_plausible_fake(candidate) and candidate not in words:
            words.append(candidate)
            if len(words) == count:
                return words
    raise RuntimeError("Could not generate enough fake words")


def make_set(level: str, seed: int) -> list[dict]:
    """A deterministic set of words for (level, seed), about half real and half fake."""
    rng = random.Random(f"{level}-{seed}")
    real_count = rng.randint(WORDS_PER_SET // 2 - 2, WORDS_PER_SET // 2 + 2)
    real = rng.sample(sorted(set(load("words")[level])), real_count)
    fake = fake_words(rng, WORDS_PER_SET - real_count)
    words = [{"word": w, "real": True} for w in real] + [{"word": w, "real": False} for w in fake]
    rng.shuffle(words)
    return words
